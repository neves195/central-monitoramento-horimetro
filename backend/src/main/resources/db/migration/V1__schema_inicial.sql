CREATE TABLE equipments (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            VARCHAR (30) NOT NULL,
    name            VARCHAR (120) NOT NULL,
    category        VARCHAR (60),
    current_hours   NUMERIC (12, 1) NOT NULL DEFAULT 0,
    active          BOOLEAN NOT NULL DEFAULT TRUE,
    created_at      TIMESTAMP NOT NULL,
    CONSTRAINT      uk_equipments_code UNIQUE (CODE)
);

CREATE TABLE maintenance_plans (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_id    BIGINT NOT NULL,
    name            VARCHAR (120) NOT NULL,
    interval_hours  NUMERIC (12, 1) NOT NULL,
    warning_hours   NUMERIC (12, 1) NOT NULL,
    last_maintenance_hours  NUMERIC (12, 1) NOT NULL,
    active          BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL,
    CONSTRAINT fk_plans_equipment FOREIGN KEY (equipment_id) REFERENCES equipments (id),
    CONSTRAINT ck_plans_interval CHECK (interval_hours > 0),
    CONSTRAINT ck_plans_warning CHECK (warning_hours >= 0)
    );

CREATE TABLE hour_meter_readings (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_id    BIGINT NOT NULL,
    hours           NUMERIC (12, 1) NOT NULL,
    read_at         TIMESTAMP NOT NULL,
    registered_by   VARCHAR(50) NOT NULL,
    created_at      TIMESTAMP NOT NULL,
    CONSTRAINT fk_readings_equipment FOREIGN KEY (equipment_id) REFERENCES equipments (id),
    CONSTRAINT ck_readings_hours  CHECK (hours >= 0)
    );

CREATE TABLE maintenance_records (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    equipment_id    BIGINT NOT NULL,
    plan_id         BIGINT,
    status          VARCHAR (20) NOT NULL,
    scheduled_date  DATE,
    performed_at    DATE,
    hours_at_maintenance NUMERIC(12, 1),
    description     VARCHAR (500) NOT NULL, 
    responsible     VARCHAR(100),
    created_at      TIMESTAMP NOT NULL,
    CONSTRAINT fk_maint_plan      FOREIGN KEY (plan_id) REFERENCES maintenance_plans (id),
    CONSTRAINT fk_maint_equipment FOREIGN KEY (equipment_id) REFERENCES equipments (id),
    CONSTRAINT ck_maint_status    CHECK (status IN ('SCHEDULED', 'COMPLETED', 'CANCELED')),
    CONSTRAINT ck_maint_hours     CHECK (hours_at_maintenance >= 0)
    ); 